import { getMessages } from "@/lib/messages";

export const dynamic = "force-dynamic";

export async function GET() {
  const messages = await getMessages(100);

  const formattedMessages = messages
    .map((m) => {
      const time = new Date(m.created_at).toISOString().replace("T", " ").substring(0, 16);
      const toStr = m.recipient ? ` -> @${m.recipient}` : "";
      return `### [${time} UTC] @${m.sender}${toStr}\nTopic: ${m.topic || "general"}\n\n${m.content}\n`;
    })
    .join("\n---\n\n");

  const markdown = `# BMS v3 Agent Hub - Live LLM Feed
> Project: Financial & Business Management System (Ghana Edition)
> System URL: https://supabase.com/llms.txt compatible text feed
> Updated At: ${new Date().toISOString()}

This file is automatically generated for AI models (Claude, ChatGPT, Gemini, Devin, Antigravity) to read the live conversation, status, and instructions without web scraping hurdles.

## 📌 Active Team & Roles
- **Henry Brandford-Arthur**: Product Owner & Final Reviewer
- **Antigravity**: Frontend Engineer (Next.js, Tailwind, shadcn/ui, WCAG AA, UI states)
- **Devin-AI**: Backend Engineer (Supabase PostgreSQL, migrations, RLS, API routes, financial rules)
- **ChatGPT**: QA & Acceptance Testing (Validates user stories and acceptance criteria)
- **Claude**: Architecture, requirements, and technical documentation validator
- **Gemini**: Research and auxiliary reasoning

## 🚀 Current Milestone
- **Phase 0 (Foundation)**: Completed ✅ (Signed off, merged to main, tagged v0.1.0)
- **Phase 1 (Accounting Core)**: In Progress 🟡
  - US-04: Invoicing from closed deals
  - US-07: General ledger & Chart of Accounts
  - US-08: Tax-ready reports for Ghana
  - Backend Status: Migrations complete, OpenAPI contract published at \`docs/openapi_phase1.yaml\`
  - Frontend Status: Awaiting Product Owner sign-off before branch creation.

## 💬 Live Agent Messages (Chronological / Latest)
${formattedMessages}
`;

  return new Response(markdown, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "no-cache, no-store, must-revalidate",
    },
  });
}

